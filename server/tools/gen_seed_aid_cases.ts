/**
 * C-197：生成 tests/dynamic_farm/fixtures/seed_aid_cases.json（种子兜底的共用用例）。每个用例按服务端规则算出 expect，
 * server/test/parcels/seed_aid.test.ts 和 tests/dynamic_farm/test_seed_aid.gd 各跑一遍，两边都要等于它。
 * 改了 seed_aid.ts 或 dynamic_farm.json 的 seed_aid 后重新生成，再逐条核对差异：
 *   pnpm --dir server exec tsx tools/gen_seed_aid_cases.ts
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { DEFAULT_CONTENT_DIR } from '../src/domain/content.js';
import { nextRollover } from '../src/parcels/energy.js';
import { applyFarmCommands, emptyFarm, welcome, type FarmCommand, type ParcelFarmState } from '../src/parcels/farm.js';
import { loadParcelRules } from '../src/parcels/rules.js';

const rules = loadParcelRules(DEFAULT_CONTENT_DIR);
/** 太平洋时间 11-22 晚 8 点（玩家日 2026-11-22，凌晨 4 点换日）。 */
const T0 = 1795406400000;
const OUT = path.join(DEFAULT_CONTENT_DIR, '..', '..', '..', 'tests', 'dynamic_farm', 'fixtures', 'seed_aid_cases.json');
const CLAIM: FarmCommand[] = [{ type: 'claim_seed_aid' }];

const saved = (s: ParcelFarmState): ParcelFarmState => JSON.parse(JSON.stringify(s));
/** 进过农场、种子用完、钱花光、没作物：赠品里只剩锄头和小屋蓝图。 */
const broke = (extra: Partial<ParcelFarmState> = {}): ParcelFarmState => {
  const s = welcome(rules, emptyFarm(), T0)!;
  delete s.bag.seed_carrot;
  return { ...s, ...extra };
};
const run = (s: ParcelFarmState, now: number): ParcelFarmState => {
  const out = applyFarmCommands(rules, s, CLAIM, now);
  if (!out.ok) throw new Error(`${out.code}`);
  return out.state;
};

interface Case { name: string; farm: ParcelFarmState; commands: FarmCommand[]; now: number }
const cases: Case[] = [];
const add = (name: string, farm: ParcelFarmState, now: number, commands = CLAIM) => cases.push({ name, farm: saved(farm), now, commands });

const rollover = nextRollover(rules, T0);
/** 今天领过，种子又用完了（三条又都满足）。 */
const given = run(broke(), T0);
delete given.bag.seed_carrot;
add('no coins, no seeds, no crops: Jasmine gives 3 carrot seeds and the day is saved', broke(), T0 + 1000);
add('given today and broke again: a second claim the same player day is refused, nothing changes', given, T0 + 60_000);
add('two claims in one batch: the second is refused, the whole batch with it', broke(), T0, [...CLAIM, ...CLAIM]);
add('just before 4 am Pacific it is still the same day', given, rollover - 1);
add('from 4 am Pacific (the next player day) the aid comes again', given, rollover);
add('8 coins cannot buy a 9-coin seed: still no money', broke({ coins: 8 }), T0);
add('9 coins buy a seed: refused for coins', broke({ coins: 9 }), T0);
add('one seed in the bag: refused for seeds', broke({ bag: { hoe_starter: 1, seed_carrot: 1 } }), T0);
add('a carrot in the bag: refused for crops', broke({ bag: { hoe_starter: 1, crop_carrot: 1 } }), T0);
add('a sown, unwatered carrot in the ground: refused for crops', broke({ tilled: ['3,4'],
  crops: { '3,4': { crop: 'crop_carrot', planted_at: T0, ripe_at: 8_640_000_000_000_000, watered_at: null } } }), T0 + 1000);
add('a growing carrot in the ground: refused for crops', broke({ tilled: ['3,4'],
  crops: { '3,4': { crop: 'crop_carrot', planted_at: T0, ripe_at: T0 + 60_000, watered_at: T0 } } }), T0 + 1000);
add('eggs, wood and stone do not count: still given', broke({ bag: { hoe_starter: 1, egg: 2, wood: 5, stone: 3 } }), T0);
const old = saved(broke()) as Partial<ParcelFarmState>;
delete old.seed_aid_day;
add('a save from before the aid (no seed_aid_day) reads as never given', old as ParcelFarmState, T0);
add('an unreadable seed_aid_day reads as never given', { ...broke(), seed_aid_day: 'yesterday' } as ParcelFarmState, T0);

const expect = (c: Case) => {
  const r = applyFarmCommands(rules, structuredClone(c.farm), c.commands, c.now);
  return r.ok ? { ok: true, bag: r.state.bag, coins: r.state.coins, seed_aid_day: r.state.seed_aid_day }
    : { ok: false, index: r.index, code: r.code, detail: r.detail ?? {} };
};
writeFileSync(OUT, `${JSON.stringify({
  _note: 'C-197 seed aid: each case runs through server/src/parcels/farm.ts (server/test/parcels/seed_aid.test.ts) and '
    + 'modules/dynamic_farm/parcel_farm.gd (tests/dynamic_farm/test_seed_aid.gd); both must give `expect`. Generated by '
    + 'server/tools/gen_seed_aid_cases.ts from the server rules (owner SEN-Q-281: no coins, no seeds, no crops -> 3 carrot seeds a day).',
  cases: cases.map(c => ({ ...c, expect: expect(c) })),
}, null, 1)}\n`);
console.log(`${cases.length} cases → ${OUT}`);
