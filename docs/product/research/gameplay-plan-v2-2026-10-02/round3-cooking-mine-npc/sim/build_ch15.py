def daily_block(arch):
    """取 '### ARCH · ...' 到下一个 '###' 之间的表与两行注。"""
    start = next(i for i, l in enumerate(md) if l.startswith(f'### {arch} ·'))
    out = []
    for l in md[start + 1:]:
        if l.startswith('### ') or l.startswith('## '):
            break
        if l.strip():
            out.append(l)
    return '\n'.join(out)

