def qbar2(slots, sel=None, bag_flash=False):
    out = []
    for k, s_ in enumerate(slots):
        if s_ is None: out.append('<div class="slot is-ghost"></div>')
        else:
            out.append(f'<div class="slot has-count{" is-selected" if k == sel else ""}">{I(s_[0], "slot-icon")}<span class="name">{s_[1]}</span><span class="count">×{s_[2]}</span></div>')
    return f"""  <nav class="quickbar{' has-selection' if sel is not None else ''}">
    <div class="slots">
        {''.join(out)}
    </div>
    <div class="bag card{' is-flash' if bag_flash else ''}">{I("icons.svg#i-bag")}<span class="chip-label">Bag</span></div>
  </nav>"""

