def I(href, cls='ic'):
    return f'<svg class="{cls}" aria-hidden="true"><use href="../{href}"/></svg>'

_hud_src = open(os.path.join(B1, 'FARM-6.html'), encoding='utf-8').read()
HUD_T = _hud_src[_hud_src.index('  <header class="hud">'):_hud_src.index('  </header>') + len('  </header>')]

def hud(energy=142, mx=200, regen='2:41', coins=230, today='Radishes ready in 1h 12m', city='Shanghai', space='Homestead', delta=None):
    h = HUD_T
    pct = max(0, min(100, round(energy * 100 / mx)))
    h = h.replace('style="--pct:71%"', f'style="--pct:{pct}%"')
    h = h.replace('<div class="energy-num">142<span class="of">/200</span></div>',
                  f'<div class="energy-num">{energy}<span class="of">/{mx}</span></div>' + (f'<span class="energy-delta {delta[1]}">{delta[0]}</span>' if delta else ''))
    h = h.replace('+1 in <b>2:41</b>', f'+1 in <b>{regen}</b>' if regen != 'Full' else '<b>Full</b>')
    h = h.replace('<span>230</span>', f'<span>{coins}</span>')
    h = h.replace('<span class="today-text">Radishes ready in 1h 12m</span>', f'<span class="today-text">{today}</span>')
    h = h.replace('<span>Shanghai</span>', f'<span>{city}</span>').replace('<span class="space">Homestead</span>', f'<span class="space">{space}</span>')
    return h

