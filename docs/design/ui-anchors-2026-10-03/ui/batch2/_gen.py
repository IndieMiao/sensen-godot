def tile(icon, name, have, need, size='', short=None, label=None):
    pct = 100 if need == 0 else min(100, round(have * 100 / need))
    if short is None: short = have < need
    c = 'need-tile' + (f' is-{size}' if size else '') + (' is-short' if short else '')
    return (f'<div class="{c}" style="--pct:{pct}"><div class="ring"><div class="core">{I(icon)}</div></div>'
            f'<div class="lbl">{label or name} <b>{have:,}</b><span class="of">/{need:,}</span></div></div>')

def qbar(slots, sel=0, bag_dot=False, inline=False):
    out = []
    for k, s in enumerate(slots):
        if s is None:
            out.append('<div class="slot is-ghost"></div>')
        else:
            icon, name, cnt = s
            out.append(f'<div class="slot has-count{" is-selected" if k == sel else ""}">{I(icon, "slot-icon")}<span class="name">{name}</span><span class="count">×{cnt}</span></div>')
    slots_html = '\n        '.join(out)
    bag = f'<div class="bag card">{I("icons.svg#i-bag")}<span class="chip-label">Bag</span>{"<span class=\"cap-dot\"></span>" if bag_dot else ""}</div>'
    return f'''  <nav class="quickbar has-selection">
    <div class="slots">
        {slots_html}
    </div>
    {bag}
  </nav>'''

def fab(icon, verb, sub, badge, cls=''):
    return (f'  <div class="switch" title="Switch action">{I("icons.svg#i-switch")}</div>\n'
            f'  <div class="fab {cls}"><div class="gear-badge">{I(badge)}</div>{I(icon)}<span class="lbl">{verb}</span><span class="sub">{sub}</span></div>')

